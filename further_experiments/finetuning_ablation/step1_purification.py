"""
import os
Step 1d: Purification test on Linear Probe.
Categories:
  - real (100): from data_split.json real_holdout[:100]
  - clean_fake (100): random from generation/outputs/final_1002 (same as previous purification test)
  - adv_lp (100): newly generated by step1_generate_adv.py (Linear Probe target)
  - adv_siglip (100): existing, for cross-target reference
  - adv_forada (100): existing, for cross-target reference
  - jpeg_q80 (100): real with JPEG Q80

Method: median3 filter, delta_logit = logit(p_med3) - logit(p_orig).

Output: linear_probe_purification.csv
"""
import os, sys, time, json
from pathlib import Path
import numpy as np
import pandas as pd
import torch
import torch.nn as nn
import torch.nn.functional as F
import torchvision.transforms as T
from PIL import Image, ImageFilter
import cv2
from transformers import CLIPModel

os.environ.setdefault('HF_TOKEN', 'REMOVED_TOKEN_USE_ENV_VAR')

BASE = Path('/home/s20204116/GEN_AI_GTG')
OUT = BASE / 'detection/finetuning_ablation'
DEVICE = torch.device('cuda:0')
LOG = OUT / 'logs/step1_purif.log'

def log(msg):
    line = f"[{time.strftime('%H:%M:%S')}] {msg}"
    print(line, flush=True)
    with open(LOG, 'a') as f:
        f.write(line + '\n')

def host(p): return Path(str(p).replace('/home/student/', '/home/s20204116/'))

# ============== Build test data (same as previous purification, plus adv_lp) ==============
rng = np.random.default_rng(42)

with open(BASE / 'detection/gaussian_fitting/data_split.json') as f:
    split = json.load(f)
real_paths = [host(p) for p in split['real_holdout'][:100]]

clean_all = sorted((BASE / 'generation/outputs/final_1002').glob('*.png'))
clean_paths = [clean_all[i] for i in sorted(rng.choice(len(clean_all), 100, replace=False))]

ADV_BASE = BASE / 'detection/multi_attack/images'
def collect(target):
    dirs = sorted([d for d in ADV_BASE.glob(f'{target}__*__pgd_eps4') if not d.name.endswith('jpeg80')])
    imgs = []
    for d in dirs: imgs.extend(sorted(d.glob('*.png')))
    return imgs

forada_pool = collect('forada')
adv_forada_paths = [forada_pool[i] for i in sorted(rng.choice(len(forada_pool), 100, replace=False))]
siglip_pool = collect('siglip')
adv_siglip_paths = [siglip_pool[i] for i in sorted(rng.choice(len(siglip_pool), 100, replace=False))]

# Linear Probe target adversarial (new)
adv_lp_paths = sorted((OUT / 'linear_probe_adv').glob('*.png'))
log(f"adv_lp dir has {len(adv_lp_paths)} images")
assert len(adv_lp_paths) == 100, f"expected 100 adv_lp, got {len(adv_lp_paths)}"


def apply_jpeg(pil, q=80):
    arr = np.array(pil); bgr = cv2.cvtColor(arr, cv2.COLOR_RGB2BGR)
    _, buf = cv2.imencode('.jpg', bgr, [cv2.IMWRITE_JPEG_QUALITY, q])
    return Image.fromarray(cv2.cvtColor(cv2.imdecode(buf, cv2.IMREAD_COLOR), cv2.COLOR_BGR2RGB))

def load_pil(p): return Image.open(p).convert('RGB').resize((256,256), Image.LANCZOS)

real_pils       = [load_pil(p) for p in real_paths]
clean_pils      = [load_pil(p) for p in clean_paths]
adv_lp_pils     = [load_pil(p) for p in adv_lp_paths]
adv_forada_pils = [load_pil(p) for p in adv_forada_paths]
adv_siglip_pils = [load_pil(p) for p in adv_siglip_paths]
jpeg_pils       = [apply_jpeg(p, 80) for p in real_pils]

def med3(pils): return [p.filter(ImageFilter.MedianFilter(size=3)) for p in pils]

CATEGORIES = [
    ('real',       real_pils,       med3(real_pils),       real_paths),
    ('clean_fake', clean_pils,      med3(clean_pils),      clean_paths),
    ('jpeg_q80',   jpeg_pils,       med3(jpeg_pils),       real_paths),
    ('adv_lp',     adv_lp_pils,     med3(adv_lp_pils),     adv_lp_paths),
    ('adv_forada', adv_forada_pils, med3(adv_forada_pils), adv_forada_paths),
    ('adv_siglip', adv_siglip_pils, med3(adv_siglip_pils), adv_siglip_paths),
]
log(f"Total samples: {sum(len(c[1]) for c in CATEGORIES)}")


# ============== Load Linear Probe ==============
log("Loading CLIP ViT-L/14 + Linear Probe classifier...")
clip_model = CLIPModel.from_pretrained('openai/clip-vit-large-patch14').to(DEVICE)
clip_model.eval()
for p in clip_model.parameters(): p.requires_grad = False

class Classifier(nn.Module):
    def __init__(s, in_dim=1024, hidden=256):
        super().__init__()
        s.net = nn.Sequential(
            nn.Linear(in_dim, hidden),
            nn.GELU(),
            nn.Dropout(0.3),
            nn.Linear(hidden, 1),
        )
    def forward(s, x): return s.net(x).squeeze(-1)

ckpt = torch.load(OUT / 'models/linear_probe.pt', map_location=DEVICE)
clf = Classifier(in_dim=ckpt['in_dim'], hidden=ckpt['hidden']).to(DEVICE)
clf.load_state_dict(ckpt['classifier_state_dict'])
clf.eval()

CLIP_MEAN = torch.tensor([.48145466,.4578275,.40821073]).view(1,3,1,1).to(DEVICE)
CLIP_STD  = torch.tensor([.26862954,.26130258,.27577711]).view(1,3,1,1).to(DEVICE)

@torch.no_grad()
def predict(pils, bs=32):
    probs = []
    for i in range(0, len(pils), bs):
        chunk = pils[i:i+bs]
        x = torch.stack([T.ToTensor()(p) for p in chunk]).to(DEVICE)
        x224 = F.interpolate(x, (224,224), mode='bilinear', align_corners=False)
        inp = (x224 - CLIP_MEAN) / CLIP_STD
        feat = clip_model.vision_model(inp).pooler_output
        logits = clf(feat)
        probs.extend(torch.sigmoid(logits).cpu().numpy().tolist())
    return probs


SAFE_EPS = 1e-6
def logit_p(p):
    p = np.clip(p, SAFE_EPS, 1-SAFE_EPS)
    return np.log(p/(1-p))

# ============== Run ==============
log("Running purification...")
rows = []
for cat, pils, m3, paths in CATEGORIES:
    t0 = time.time()
    po = predict(pils)
    pm = predict(m3)
    for i in range(len(pils)):
        rows.append({
            'category': cat,
            'image_id': Path(paths[i]).stem,
            'prob_orig': float(po[i]),
            'prob_med3': float(pm[i]),
            'delta_logit': float(logit_p(pm[i]) - logit_p(po[i])),
        })
    log(f"  {cat} ({len(pils)}): {time.time()-t0:.1f}s, p_orig={np.mean(po):.3f} p_med3={np.mean(pm):.3f}")

df = pd.DataFrame(rows)
df.to_csv(OUT / 'linear_probe_purification.csv', index=False)
log(f"Saved linear_probe_purification.csv ({len(df)} rows)")
log("DONE Step 1d")
